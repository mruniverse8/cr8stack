import argparse
from collections import Counter
from datetime import datetime
import html
import importlib.util
import json
import os
from pathlib import Path
from urllib.parse import quote
from zoneinfo import ZoneInfo


HELPER = Path(__file__).resolve().parents[2] / 'swarm-cloud' / 'scripts' / 'cloud_tasks.py'


def registry():
    spec = importlib.util.spec_from_file_location('swarm_run_registry', HELPER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def cell(value):
    value = html.escape(str(value if value is not None else 'unknown'), quote=False)
    return ' '.join(value.split()).replace('|', '&#124;').replace(chr(96), '&#96;')


def link(path, output, label):
    relative = quote(os.path.relpath(path, output.parent), safe='/')
    return '[' + cell(label) + '](' + relative + ')'


def reported_blocker(task, root):
    if task['backend'] == 'sub':
        native_result = root / 'results' / task['id'] / 'native-result.md'
        if native_result.is_file():
            text = native_result.read_text().strip()
            if text.startswith(('BLOCKED', 'ISSUES')) or task['status'] == 'failed':
                return text[:180]
    artifact = task.get('artifact')
    if not artifact:
        return None
    try:
        path = (root / artifact['path']).resolve()
        if not path.is_relative_to(root.resolve()):
            return None
        snapshot = json.loads(path.read_text())
        turn = max(snapshot.get('turns', []), key=lambda entry: entry.get('startedAt') or 0)
        if turn.get('error'):
            return str(turn['error'])[:180]
        finals = [entry['text'] for entry in turn.get('items', [])
                  if entry.get('type') == 'agentMessage' and entry.get('phase') == 'final_answer']
        for text in finals:
            text = text.strip()
            if text.startswith((chr(96) * 3, '~~~')):
                text = '\n'.join(text.splitlines()[1:-1])
            try:
                result = json.loads(text)
            except ValueError:
                if text.startswith('BLOCKED'):
                    return text[:180]
                continue
            if isinstance(result, dict) and result.get('status') in ('BLOCKED', 'ISSUES'):
                reason = result.get('reason') or result.get('notes') or result.get('explanation') or 'Inspect worker output'
                return result['status'] + ' reported: ' + str(reason)[:180]
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return None


def next_step(task, tasks):
    if task['result'] == 'accepted':
        return 'Accepted'
    if task['worker_state'] == 'submission_unknown':
        return 'Reconcile submission token and pending identity before retry'
    blockers = [dep for dep in task['dependencies'] if tasks[dep]['result'] != 'accepted']
    if blockers:
        return 'Waiting for ' + ', '.join(blockers)
    if task['worker_state'] == 'failed':
        return 'Inspect failure evidence and define the correction'
    if task['worker_state'] == 'unknown':
        return 'Refresh saved worker identity'
    if task['worker_state'] in ('running', 'pending'):
        return 'Refresh progress'
    if task['worker_state'] == 'completed':
        return 'Inspect returned result and verify acceptance'
    return 'Ready to schedule'


def scan(project, output, timezone):
    project = project.resolve()
    helper = registry()
    generated = datetime.now(ZoneInfo(timezone)).strftime('%Y-%m-%d %H:%M %Z')
    lines = ['# Swarm status', '', 'Generated by $swarm-status.', '',
             'Project ' + cell(project.name) + '. Updated ' + generated + '.', '',
             'Saved observations and local acceptance evidence. Live refresh is available through $swarm-check.', '']
    counts = Counter()
    for path in sorted((project / '.pstack' / 'runs').glob('*/state.json')):
        root = path.parent
        lines.extend(['## ' + cell(root.name), ''])
        try:
            if not root.resolve().is_relative_to(project):
                raise ValueError('Run directory points outside this project')
            state = helper.load(root)
            report = helper.report(root, state, offline=True)
        except (OSError, ValueError, KeyError, TypeError, AttributeError, helper.RunError) as error:
            counts['errors'] += 1
            lines.extend(['Inspection error. ' + cell(str(error)[:200]) + '. ' +
                          link(path, output, 'Registry') + '.', ''])
            continue
        tasks = {task['id']: task for task in report['tasks']}
        accepted = sum(task['result'] == 'accepted' for task in tasks.values())
        complete = accepted == len(tasks)
        counts['complete' if complete else 'unfinished'] += 1
        backends = ', '.join(sorted({task['backend'] for task in tasks.values()}))
        references = [link(path, output, 'Registry')]
        for name, label in [('results', 'Worker results'), ('decisions.tsv', 'Decision trail')]:
            if (root / name).exists():
                references.append(link(root / name, output, label))
        lines.extend(['Run ID ' + cell(report['run_id']) + '. ' +
                      str(accepted) + '/' + str(len(tasks)) + ' accepted. ' +
                      ('Complete' if complete else 'Unfinished') + '. Backend ' + cell(backends) +
                      '. Scheduling ' + cell(report['scheduling']) + '.', '',
                      ' · '.join(references), '',
                      '| Worker | Backend | Worker ID / host | State / acceptance | Last observed | Blocker or next action |',
                      '| --- | --- | --- | --- | --- | --- |'])
        raw_tasks = {task['id']: task for task in state['tasks']}
        for task in tasks.values():
            identity = task['task_id'] or task.get('client_thread_id') or 'unassigned'
            if task.get('host_id'):
                identity += ' / ' + task['host_id']
            blocker = reported_blocker(raw_tasks[task['id']], root) if task['result'] != 'accepted' else None
            action = blocker or next_step(task, tasks)
            if task.get('detail') and task['worker_state'] in ('unknown', 'failed'):
                action += '. ' + task['detail'][:180]
            artifact = task.get('artifact')
            worker = cell(task['id'])
            if artifact and (root / artifact['path']).is_file():
                worker = link(root / artifact['path'], output, task['id'])
            elif task['backend'] == 'sub':
                native_result = root / 'results' / task['id'] / 'native-result.md'
                if native_result.is_file():
                    worker = link(native_result, output, task['id'])
            row = [worker, cell(task['backend']), cell(identity),
                   cell(task['worker_state'] + ' / ' + task['result']),
                   cell(task.get('last_checked') or 'unobserved'), cell(action)]
            lines.append('| ' + ' | '.join(row) + ' |')
        lines.append('')
        if report['pause_reason']:
            lines.extend(['Scheduling pause. ' + cell(report['pause_reason']) + '.', ''])
        if report['plan_changed']:
            lines.extend(['Plan changed or unavailable. Reconcile the plan before continuing.', ''])
        if report['version'] == 1:
            lines.extend(['Version 1 recovery requires reconciling desktop identities into a revised run.', ''])
        if not complete:
            native_only = all(task['backend'] == 'sub' for task in tasks.values())
            skill = '$swarm-sub' if native_only else '$swarm-cloud'
            lines.extend(['Continuation request', '', '~~~text',
                          skill + ' Resume the existing run at ' + json.dumps(str(root)) +
                          '. Refresh known workers, reconcile uncertain or blocked work, and continue the unfinished items.',
                          '~~~', ''])
    if not counts:
        lines.extend(['No saved swarm registries found under .pstack/runs/.', ''])
    lines.extend(['Coverage includes saved Cloud and native runs. Older unrecorded native sessions require their original conversation.', ''])
    summary = (str(counts['complete']) + ' complete, ' + str(counts['unfinished']) +
               ' unfinished, ' + str(counts['errors']) + ' inspection errors.')
    lines[6:6] = [summary, '']
    helper.atomic(output, '\n'.join(lines))
    return summary


def main():
    parser = argparse.ArgumentParser(description='Write a concise project swarm inventory from saved registries.')
    parser.add_argument('--project', type=Path, default=Path.cwd())
    parser.add_argument('--output', type=Path)
    parser.add_argument('--timezone', default='UTC')
    args = parser.parse_args()
    project = args.project.resolve()
    if not project.is_dir():
        parser.error('Project directory does not exist')
    output = args.output.resolve() if args.output else project / 'SWARM-STATUS.md'
    summary = scan(project, output, args.timezone)
    print(str(output))
    print(summary)


if __name__ == '__main__':
    main()
